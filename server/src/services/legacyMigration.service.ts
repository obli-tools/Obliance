// ── Migration: reduced legacy agent → full agent (nt6 MSI) ──────────────────
//
// The reduced legacy agent (agent/cmd/legacy, obliance-legacy.exe installed
// with `sc create OblianceAgent`, 23 commands, no self-update) can run a
// PowerShell script (run_script). The migration sends one, PowerShell 2.0
// compatible (Windows Server 2008 R2 / Windows 7 ship 2.0), which:
//   1. picks the nt6 MSI of the WINDOWS architecture (x64 / x86 — not the
//      legacy exe's own, a 32-bit exe can run on a 64-bit Windows);
//   2. reads the server URL + API key THE DEVICE ALREADY USES, the way the
//      legacy agent resolves them (config.json < HKLM\SOFTWARE\OblianceAgent <
//      the service's --url / --key arguments): the key never leaves the
//      device, never sits in the command queue / history, and is by
//      construction the key of the device's own tenant;
//   3. downloads the MSI from that server (BITS, WebClient fallback) into
//      %ProgramData%\OblianceMigrate (ACL: SYSTEM + Administrators only) and
//      checks its SHA-256 (given by the server in the script);
//   4. writes a .cmd and runs it as a one-shot SYSTEM scheduled task (it
//      outlives the legacy service): wait ~2 min (the run_script ack goes out
//      with the next push), stop + delete the OblianceAgent service, move the
//      old exe aside (the MSI installs C:\Program Files\OblianceAgent\
//      obliance-agent.exe — the legacy install used that same path),
//      msiexec /i <msi> SERVERURL=… APIKEY=… /qn /l*v <log>; success → old
//      exe removed; failure → old exe and service restored (sc create with the
//      original command line) and restarted.
// Identity: the full agent keeps %ProgramData%\OblianceAgent\config.json and
// resolves the same device UUID (SMBIOS UUID, then the disk-serial UUID v5 —
// agent/machine_uuid.go vs cmd/legacy/main.go): the device row is reused.
//
// State: devices.legacy_migration (shared LegacyMigrationState). pending →
// (script ack) scheduled | failed → done when the device pushes again as a
// modern agent (routes/agent.routes.ts, completedState).

export const LEGACY_MIGRATION_SOURCE = 'legacy_migration';
export const LEGACY_MIGRATION_TASK = 'Obliance-LegacyMigration';
/** The queued script waits this long for a device that is offline. */
export const LEGACY_MIGRATION_EXPIRES_S = 7 * 86400;
/** run_script timeout on the agent (download of the MSI included). */
export const LEGACY_MIGRATION_SCRIPT_TIMEOUT_S = 900;

const SHA_RE = /^[0-9a-f]{64}$/;
const URL_RE = /^https?:\/\/[A-Za-z0-9.-]+(?::\d{1,5})?(?:\/[A-Za-z0-9._~/-]*)?$/;

/** A public server URL usable as fallback (the device's own URL comes first). */
export function migrationFallbackServerUrl(): string | null {
  for (const v of [process.env.SERVER_URL, process.env.APP_URL, process.env.CLIENT_ORIGIN]) {
    const s = String(v ?? '').trim().replace(/\/+$/, '');
    if (!s || /\/\/(localhost|127\.|\[::1\])/i.test(s)) continue;
    if (URL_RE.test(s)) return s;
  }
  return null;
}

const psQuote = (s: string) => `'${s.replace(/'/g, "''")}'`;

/**
 * The run_script content (runtime powershell). Only validated values are
 * embedded (hex digests, a URL of a restricted charset): no injection path.
 */
export function buildLegacyMigrationScript(opts: {
  sha256X64: string | null;
  sha256X86: string | null;
  fallbackServerUrl: string | null;
}): string {
  const x64 = opts.sha256X64 && SHA_RE.test(opts.sha256X64) ? opts.sha256X64 : '';
  const x86 = opts.sha256X86 && SHA_RE.test(opts.sha256X86) ? opts.sha256X86 : '';
  const fb = opts.fallbackServerUrl && URL_RE.test(opts.fallbackServerUrl) ? opts.fallbackServerUrl : '';
  const L: string[] = [
    '# Obliance - migration from the legacy agent to the full agent (nt6 MSI).',
    '# Generated by the Obliance server. PowerShell 2.0 compatible.',
    "$ErrorActionPreference = 'Continue'",
    'try { [Net.ServicePointManager]::SecurityProtocol = 3072 } catch { }',
    "function Fail($code, $msg) { Write-Output ('MIGRATION FAILED: ' + $msg); exit $code }",
    `$sha64 = ${psQuote(x64)}`,
    `$sha86 = ${psQuote(x86)}`,
    `$fallbackUrl = ${psQuote(fb)}`,
    "$svcName = 'OblianceAgent'",
    `$taskName = ${psQuote(LEGACY_MIGRATION_TASK)}`,
    '',
    '# 1. Architecture of Windows (not of this process).',
    "$is64 = ($env:PROCESSOR_ARCHITECTURE -eq 'AMD64') -or ($env:PROCESSOR_ARCHITEW6432 -eq 'AMD64')",
    `if ($is64) { $file = ${psQuote(AGENT_MSI_NT6_X64)}; $sha = $sha64 } else { $file = ${psQuote(AGENT_MSI_NT6_X86)}; $sha = $sha86 }`,
    "if (-not $sha) { Fail 2 ('the server has no ' + $file + ' for this architecture') }",
    "if ($env:ProgramData) { $pd = $env:ProgramData } else { $pd = 'C:\\ProgramData' }",
    '',
    '# 2. Server URL + API key, resolved like the legacy agent: config.json < registry < service arguments.',
    'function Unescape-Json([string]$v) {',
    "  $v = [regex]::Replace($v, '\\\\u([0-9a-fA-F]{4})', { param($m) [string][char][Convert]::ToInt32($m.Groups[1].Value, 16) })",
    "  return $v.Replace('\\/', '/').Replace('\\\\', '\\')",
    '}',
    "$serverUrl = ''",
    "$apiKey = ''",
    "$cfgPath = Join-Path $pd 'OblianceAgent\\config.json'",
    'if (Test-Path -LiteralPath $cfgPath) {',
    '  $raw = [IO.File]::ReadAllText($cfgPath)',
    "  if ($raw -match '\"serverUrl\"\\s*:\\s*\"((?:[^\"\\\\]|\\\\.)*)\"') { $serverUrl = Unescape-Json $matches[1] }",
    "  if ($raw -match '\"apiKey\"\\s*:\\s*\"((?:[^\"\\\\]|\\\\.)*)\"') { $apiKey = Unescape-Json $matches[1] }",
    '}',
    "try { $reg = Get-ItemProperty -Path 'HKLM:\\SOFTWARE\\OblianceAgent' -ErrorAction Stop; if ($reg.ServerUrl -and $reg.ApiKey) { $serverUrl = [string]$reg.ServerUrl; $apiKey = [string]$reg.ApiKey } } catch { }",
    "$imagePath = ''",
    "try { $imagePath = [string](Get-ItemProperty -Path ('HKLM:\\SYSTEM\\CurrentControlSet\\Services\\' + $svcName) -ErrorAction Stop).ImagePath } catch { Fail 3 'service OblianceAgent not found' }",
    "if ($imagePath -match '--url[=\\s]+\"?([^\"\\s]+)') { $serverUrl = $matches[1] }",
    "if ($imagePath -match '--key[=\\s]+\"?([^\"\\s]+)') { $apiKey = $matches[1] }",
    "$serverUrl = $serverUrl.Trim().Trim('\"').TrimEnd('/')",
    "$apiKey = $apiKey.Trim().Trim('\"')",
    'if (-not $serverUrl) { $serverUrl = $fallbackUrl }',
    "if ($serverUrl -notmatch '^https?://[A-Za-z0-9.\\-]+(:\\d{1,5})?(/[A-Za-z0-9._~/\\-]*)?$') { Fail 4 ('unusable server URL: ' + $serverUrl) }",
    "if ($apiKey -notmatch '^[A-Za-z0-9._~+/=\\-]{8,256}$') { Fail 4 'API key of the agent not found (config.json / registry / service arguments)' }",
    '',
    '# 3. Old service command line (restored if the MSI fails).',
    "if ($imagePath -notmatch '^[A-Za-z0-9 :\\\\._()\\-\"/=+~,]+$') { Fail 5 'the service command line contains characters that cannot be restored safely' }",
    "if ($imagePath -match '^\\s*\"([^\"]+)\"') { $oldExe = $matches[1] } elseif ($imagePath -match '^\\s*(\\S+)') { $oldExe = $matches[1] } else { Fail 5 'cannot read the service executable' }",
    '$exeName = [IO.Path]::GetFileName($oldExe)',
    "$dir = Join-Path $pd 'OblianceMigrate'",
    "if ($dir -match '[\\s%^&!\"]') { Fail 5 ('unsupported ProgramData path: ' + $dir) }",
    'New-Item -ItemType Directory -Force -Path $dir | Out-Null',
    "& icacls.exe $dir /inheritance:r /grant:r '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' | Out-Null",
    '$msi = Join-Path $dir $file',
    '',
    '# 4. Download (BITS, then WebClient) + SHA-256.',
    "$url = $serverUrl + '/api/agent/download/' + $file",
    'if (Test-Path -LiteralPath $msi) { Remove-Item -LiteralPath $msi -Force }',
    "$dlErr = ''",
    'try { Import-Module BitsTransfer -ErrorAction Stop; Start-BitsTransfer -Source $url -Destination $msi -ErrorAction Stop } catch { $dlErr = $_.Exception.Message }',
    'if (-not (Test-Path -LiteralPath $msi)) {',
    "  try { (New-Object System.Net.WebClient).DownloadFile($url, $msi) } catch { Fail 6 ('download failed (' + $url + '): BITS: ' + $dlErr + ' / WebClient: ' + $_.Exception.Message) }",
    '}',
    '$alg = $null',
    'try { $alg = New-Object System.Security.Cryptography.SHA256CryptoServiceProvider } catch { $alg = New-Object System.Security.Cryptography.SHA256Managed }',
    '$fs = [IO.File]::OpenRead($msi)',
    "try { $got = ([BitConverter]::ToString($alg.ComputeHash($fs)) -replace '-', '').ToLower() } finally { $fs.Close() }",
    "if ($got -ne $sha) { Remove-Item -LiteralPath $msi -Force; Fail 7 ('SHA-256 mismatch for ' + $file + ': ' + $got) }",
    '',
    '# 5. The replacement runs as a one-shot SYSTEM task (it outlives the legacy service).',
    "$log = Join-Path $dir 'migrate.log'",
    "$bak = Join-Path $dir 'obliance-legacy-backup.exe'",
    "$binArg = $imagePath.Replace('\"', '\\\"')",
    '$c = @()',
    "$c += '@echo off'",
    "$c += ('echo [%date% %time%] migration start >> \"' + $log + '\"')",
    "$c += 'ping -n 121 127.0.0.1 >nul'",
    "$c += ('sc stop ' + $svcName + ' >> \"' + $log + '\" 2>&1')",
    "$c += 'set /a n=0'",
    "$c += ':waitstop'",
    "$c += ('sc query ' + $svcName + ' | find \"STOPPED\" >nul && goto stopped')",
    "$c += 'set /a n+=1'",
    "$c += 'if %n% GEQ 30 goto stopped'",
    "$c += 'ping -n 3 127.0.0.1 >nul'",
    "$c += 'goto waitstop'",
    "$c += ':stopped'",
    "$c += ('taskkill /F /IM \"' + $exeName + '\" >> \"' + $log + '\" 2>&1')",
    "$c += ('sc delete ' + $svcName + ' >> \"' + $log + '\" 2>&1')",
    "$c += 'ping -n 4 127.0.0.1 >nul'",
    "$c += ('if exist \"' + $oldExe + '\" move /Y \"' + $oldExe + '\" \"' + $bak + '\" >> \"' + $log + '\" 2>&1')",
    "$c += ('start \"\" /wait msiexec.exe /i \"' + $msi + '\" SERVERURL=\"' + $serverUrl + '\" APIKEY=\"' + $apiKey + '\" /qn /norestart /l*v \"' + (Join-Path $dir 'msi.log') + '\"')",
    "$c += 'set rc=%errorlevel%'",
    "$c += ('echo [%date% %time%] msiexec exit code %rc% >> \"' + $log + '\"')",
    "$c += 'if \"%rc%\"==\"0\" goto ok'",
    "$c += 'if \"%rc%\"==\"3010\" goto ok'",
    "$c += ('if exist \"' + $bak + '\" move /Y \"' + $bak + '\" \"' + $oldExe + '\" >> \"' + $log + '\" 2>&1')",
    "$c += ('sc create ' + $svcName + ' binPath= \"' + $binArg + '\" start= auto DisplayName= \"Obliance Monitoring Agent\" >> \"' + $log + '\" 2>&1')",
    "$c += ('sc start ' + $svcName + ' >> \"' + $log + '\" 2>&1')",
    "$c += ('echo [%date% %time%] MSI failed - legacy agent restored >> \"' + $log + '\"')",
    "$c += 'goto end'",
    "$c += ':ok'",
    "$c += ('del /F /Q \"' + $bak + '\" >> \"' + $log + '\" 2>&1')",
    "$c += ('del /F /Q \"' + $msi + '\" >nul 2>&1')",
    "$c += ('echo [%date% %time%] migrated to the full agent >> \"' + $log + '\"')",
    "$c += ':end'",
    "$c += ('schtasks /Delete /TN \"' + $taskName + '\" /F >nul 2>&1')",
    "$c += '(goto) 2>nul & del /F /Q \"%~f0\"'",
    "$cmdPath = Join-Path $dir 'migrate.cmd'",
    "[IO.File]::WriteAllText($cmdPath, (($c -join \"`r`n\") + \"`r`n\"), [Text.Encoding]::ASCII)",
    '& schtasks.exe /Delete /TN $taskName /F 2>&1 | Out-Null',
    '$out = & schtasks.exe /Create /TN $taskName /TR $cmdPath /SC ONCE /ST 23:59 /RU SYSTEM /RL HIGHEST /F 2>&1',
    "if ($LASTEXITCODE -ne 0) { Fail 8 ('schtasks /Create failed: ' + ($out | Out-String)) }",
    '$out = & schtasks.exe /Run /TN $taskName 2>&1',
    "if ($LASTEXITCODE -ne 0) { Fail 8 ('schtasks /Run failed: ' + ($out | Out-String)) }",
    "Write-Output ('MIGRATION SCHEDULED: ' + $file + ' (sha256 ' + $sha + ') from ' + $serverUrl + ' - the service is replaced in about 2 minutes; log: ' + $log)",
    'exit 0',
  ];
  return L.join('\r\n') + '\r\n';
}

const asState = (raw: unknown): LegacyMigrationState | null => {
  if (!raw) return null;
  try {
    const v = typeof raw === 'string' ? JSON.parse(raw) : raw;
    return v && typeof v === 'object' && typeof (v as any).state === 'string' ? v as LegacyMigrationState : null;
  } catch { return null; }
};

export type MigrationRefusal = { status: number; error: string; code: string };

export const legacyMigrationService = {
  /**
   * The stored state once the device pushes as a modern agent: 'done' (null =
   * nothing to write: no migration, already done, still the legacy agent).
   */
  completedState(stored: unknown, flavor: 'modern' | 'legacy', agentBuild: string | null, agentVersion: string | null | undefined): LegacyMigrationState | null {
    const st = asState(stored);
    if (!st || st.state === 'done' || flavor !== 'modern') return null;
    return { ...st, state: 'done', doneAt: new Date().toISOString(), agentBuild: agentBuild ?? null, agentVersion: agentVersion ?? null, error: null };
  },

  /** The state to show: the command's outcome folded into a pending one. */
  async view(stored: unknown, deviceId: number): Promise<LegacyMigrationState | null> {
    const st = asState(stored);
    if (!st || st.state === 'done' || !st.commandId) return st;
    const cmd = await db('command_queue').where({ id: st.commandId, device_id: deviceId }).first('status', 'result');
    if (!cmd) return st;
    const result = typeof cmd.result === 'string' ? (() => { try { return JSON.parse(cmd.result); } catch { return null; } })() : cmd.result;
    const exitCode = typeof result?.exitCode === 'number' ? result.exitCode : null;
    const out = `${result?.stdout ?? ''}\n${result?.stderr ?? ''}`.trim();
    if (cmd.status === 'success' && (exitCode === null || exitCode === 0)) return { ...st, state: 'scheduled' };
    if (cmd.status === 'success' || ['failure', 'timeout', 'cancelled'].includes(cmd.status)) {
      const m = /MIGRATION FAILED: ([^\r\n]+)/.exec(out);
      const err = m?.[1] ?? (typeof result?.error === 'string' && result.error ? result.error : null) ?? (exitCode !== null ? `exit code ${exitCode}` : cmd.status);
      return { ...st, state: 'failed', error: String(err).slice(0, 400) };
    }
    return st;
  },

  /**
   * Queue the migration of one device. `scopeTenantId`: the request's tenant
   * (master = any tenant, the command goes to the DEVICE's tenant; any other
   * tenant = its own devices only). Authorization (admin + write on the
   * device) is the route's; this re-checks the device-level conditions.
   */
  async request(deviceId: number, scopeTenantId: number, userId: number | null): Promise<
    { ok: true; tenantId: number; hostname: string; commandId: string; state: LegacyMigrationState } | ({ ok: false } & MigrationRefusal)
  > {
    const q = db('devices').where({ id: deviceId });
    if (!isGodView(scopeTenantId)) q.where({ tenant_id: scopeTenantId });
    const dev = await q.first('id', 'tenant_id', 'hostname', 'os_type', 'os_arch', 'agent_flavor', 'approval_status', 'status',
      'privacy_mode_enabled', 'api_key_id', 'legacy_migration');
    if (!dev) return { ok: false, status: 404, code: 'not_found', error: 'Device not found' };
    if (dev.agent_flavor !== 'legacy') return { ok: false, status: 409, code: 'not_legacy', error: 'This device does not run the legacy agent' };
    if (String(dev.os_type ?? '').toLowerCase() !== 'windows') return { ok: false, status: 409, code: 'not_windows', error: 'Only a Windows device can be migrated' };
    if (dev.approval_status !== 'approved' || ['suspended', 'pending_uninstall'].includes(dev.status)) {
      return { ok: false, status: 409, code: 'not_eligible', error: 'The device is not approved, suspended or being uninstalled' };
    }
    if (dev.privacy_mode_enabled) return { ok: false, status: 423, code: 'privacy_mode', error: 'Privacy mode is active on the device' };
    // The device's own key (same tenant): the new agent re-enrols with it. It
    // is read on the device by the script — the server never sends it.
    const key = dev.api_key_id
      ? await db('agent_api_keys').where({ id: dev.api_key_id, tenant_id: dev.tenant_id }).first('id')
      : null;
    if (!key) return { ok: false, status: 409, code: 'no_api_key', error: 'The API key this device enrolled with no longer exists' };
    const cur = asState(dev.legacy_migration);
    if (cur?.commandId && cur.state === 'pending') {
      const c = await db('command_queue').where({ id: cur.commandId, device_id: dev.id }).first('status');
      if (c && ['pending', 'sent', 'ack_running'].includes(c.status)) {
        return { ok: false, status: 409, code: 'in_progress', error: 'A migration is already in progress for this device' };
      }
    }
    const [x64, x86] = await Promise.all([getDistFileInfo(AGENT_MSI_NT6_X64, { fresh: true }), getDistFileInfo(AGENT_MSI_NT6_X86, { fresh: true })]);
    const archX86 = ['386', 'x86', 'i386', 'i686'].includes(String(dev.os_arch ?? '').toLowerCase());
    // A 64-bit legacy exe ⇒ a 64-bit Windows: the x64 MSI is required. A
    // 32-bit one may run on either: the script picks, at least one is needed.
    if (!archX86 && !x64) return { ok: false, status: 409, code: 'msi_missing', error: `${AGENT_MSI_NT6_X64} is not available on this server` };
    if (archX86 && !x64 && !x86) return { ok: false, status: 409, code: 'msi_missing', error: `${AGENT_MSI_NT6_X86} / ${AGENT_MSI_NT6_X64} are not available on this server` };

    const content = buildLegacyMigrationScript({
      sha256X64: x64?.sha256 ?? null,
      sha256X86: x86?.sha256 ?? null,
      fallbackServerUrl: migrationFallbackServerUrl(),
    });
    const { commandService } = await import('./command.service');
    const cmd = await commandService.enqueue({
      deviceId: dev.id,
      tenantId: dev.tenant_id,
      type: 'run_script',
      payload: { runtime: 'powershell', content, timeoutSeconds: LEGACY_MIGRATION_SCRIPT_TIMEOUT_S },
      priority: 'high',
      expiresInSeconds: LEGACY_MIGRATION_EXPIRES_S,
      sourceType: LEGACY_MIGRATION_SOURCE,
      createdBy: userId ?? undefined,
    });
    const state: LegacyMigrationState = {
      state: 'pending', requestedAt: new Date().toISOString(), requestedBy: userId, commandId: cmd.id,
      doneAt: null, agentVersion: null, agentBuild: null, error: null,
    };
    await db('devices').where({ id: dev.id, tenant_id: dev.tenant_id }).update({ legacy_migration: JSON.stringify(state), updated_at: new Date() });
    logger.info({ deviceId: dev.id, tenantId: dev.tenant_id, commandId: cmd.id }, 'Legacy agent migration queued');
    return { ok: true, tenantId: dev.tenant_id, hostname: dev.hostname, commandId: cmd.id, state };
  },
};
